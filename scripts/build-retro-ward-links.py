"""Build pixel-style inner maps and geographic links from the main map's ward file."""
import json
import math
from collections import defaultdict
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
wards = json.loads((ROOT / 'data/map-wards.json').read_text())['features']
boroughs = defaultdict(list)
for ward in wards:
    boroughs[ward['properties']['borough'].lower()].append(ward)

def trace(mask, width, height):
    edges = {}
    def add(a, b): edges.setdefault(a, []).append(b)
    for y in range(height):
        for x in range(width):
            if not mask(x, y): continue
            if y == 0 or not mask(x, y-1): add((x,y), (x+1,y))
            if x == width-1 or not mask(x+1,y): add((x+1,y), (x+1,y+1))
            if y == height-1 or not mask(x,y+1): add((x+1,y+1), (x,y+1))
            if x == 0 or not mask(x-1,y): add((x,y+1), (x,y))
    paths = []
    while edges:
        start = next(iter(edges)); p = start; ring = []
        while True:
            ring.append(p); choices = edges[p]; nxt = choices.pop()
            if not choices: del edges[p]
            p = nxt
            if p == start: break
        corners = [p for i,p in enumerate(ring) if
                   (p[0]-ring[i-1][0])*(ring[(i+1)%len(ring)][1]-p[1]) !=
                   (p[1]-ring[i-1][1])*(ring[(i+1)%len(ring)][0]-p[0])]
        if corners: paths.append('M'+'L'.join(f'{x*3} {y*3}' for x,y in corners)+'Z')
    return ''.join(paths)

def interior_point(geometry):
    # Area centroid first, with an interior grid point for concave shapes or holes.
    rings = geometry['coordinates']
    outer = rings[0]; cross_sum = cx = cy = 0
    for a,b in zip(outer,outer[1:]+outer[:1]):
        cross = a[0]*b[1]-b[0]*a[1]
        cross_sum += cross; cx += (a[0]+b[0])*cross; cy += (a[1]+b[1])*cross
    centre = (cx/(3*cross_sum),cy/(3*cross_sum))
    def ring_contains(p, ring):
        x,y = p; result = False
        for a,b in zip(ring,ring[1:]+ring[:1]):
            if (a[1]>y)!=(b[1]>y) and x<(b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0]: result = not result
        return result
    def contains(p): return ring_contains(p,outer) and not any(ring_contains(p,r) for r in rings[1:])
    if not contains(centre):
        lo = [min(p[i] for p in outer) for i in [0,1]]
        hi = [max(p[i] for p in outer) for i in [0,1]]
        candidates = [(lo[0]+(x+.5)*(hi[0]-lo[0])/60,lo[1]+(y+.5)*(hi[1]-lo[1])/60)
                      for x in range(60) for y in range(60)]
        centre = min((p for p in candidates if contains(p)),key=lambda p:(p[0]-centre[0])**2+(p[1]-centre[1])**2)
    return [round(centre[1],6),round(centre[0],6)]

regions = {}
for slug, features in sorted(boroughs.items()):
    features.sort(key=lambda f:f['properties']['code'])
    points = [p for f in features for ring in f['geometry']['coordinates'] for p in ring]
    xmin,xmax = min(p[0] for p in points),max(p[0] for p in points)
    ymin,ymax = min(p[1] for p in points),max(p[1] for p in points)
    aspect = math.cos(math.radians((ymin+ymax)/2))
    scale = 116/max((xmax-xmin)*aspect,ymax-ymin)
    width = math.ceil((xmax-xmin)*aspect*scale)+2
    height = math.ceil((ymax-ymin)*scale)+2
    labels = Image.new('I',(width,height)); draw = ImageDraw.Draw(labels)
    for i,f in enumerate(features,1):
        for j,ring in enumerate(f['geometry']['coordinates']):
            draw.polygon([(1+(p[0]-xmin)*aspect*scale,1+(ymax-p[1])*scale) for p in ring],fill=i if j==0 else 0)
    pixels = labels.load(); areas = []; borders = []
    for i,f in enumerate(features,1):
        path = trace(lambda x,y:pixels[x,y]==i,width,height)
        if not path: raise ValueError(f"Ward too small for retro grid: {f['properties']['name']}")
        props = f['properties']
        areas.append({'name':props['name'],'confirmedName':True,'wardCode':props['code'],
                      'point':interior_point(f['geometry']),'wardNumber':None,'path':path})
    for y in range(height):
        for x in range(width):
            if not pixels[x,y]: continue
            if x+1<width and pixels[x+1,y] and pixels[x+1,y]!=pixels[x,y]: borders.append(f'M{(x+1)*3} {y*3}v3')
            if y+1<height and pixels[x,y+1] and pixels[x,y+1]!=pixels[x,y]: borders.append(f'M{x*3} {(y+1)*3}h3')
    regions[slug]={'viewBox':f'-16 -16 {width*3+32} {height*3+32}','areas':areas,
                   'borders':''.join(borders),'outline':trace(lambda x,y:pixels[x,y]!=0,width,height)}
(ROOT/'js/home-region-shapes.mjs').write_text('/* Generated by scripts/build-retro-ward-links.py from data/map-wards.json. */\nexport const regionShapes = '+json.dumps(regions,separators=(',',':'))+';\n')
print(f'Prepared {len(regions)} retro boroughs and {sum(len(r["areas"]) for r in regions.values())} linked wards.')
